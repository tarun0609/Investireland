// Copies the shared, HTML-escaping email template into functions/shared so the
// Cloud Functions bundle is self-contained (firebase deploy uploads only functions/).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'functions', 'shared');
mkdirSync(out, { recursive: true });
const banner = '// GENERATED by functions/scripts/sync-shared.mjs - do not edit.\n';
writeFileSync(join(out, 'escapeHtml.ts'), banner + readFileSync(join(root, 'src', 'utils', 'escapeHtml.ts'), 'utf8'));
writeFileSync(
  join(out, 'emailTemplate.ts'),
  banner + readFileSync(join(root, 'server', 'emailTemplate.ts'), 'utf8').replace("'../src/utils/escapeHtml'", "'./escapeHtml'")
);
console.log('Synced shared email template into functions/shared');
